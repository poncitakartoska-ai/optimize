export function getTweaksForProfile(
  mode: 'max_fps' | 'balanced' | 'minimal'
): LowLevelTweakItem[] {
  if (mode === 'max_fps') {
    return HUNDRED_TWENTY_FPS_TWEAKS;
  }
  if (mode === 'balanced') {
    return HUNDRED_TWENTY_FPS_TWEAKS.filter(
      (t) => t.minProfile === 'minimal' || t.minProfile === 'balanced'
    );
  }
  return HUNDRED_TWENTY_FPS_TWEAKS.filter((t) => t.minProfile === 'minimal');
}
